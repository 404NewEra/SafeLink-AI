def fetch_kma_data(url, params=None):
    try:
        print(f"요청 중: {url.split('?')[0]}...")
        response = requests.get(url, params=params)
        response.raise_for_status() # HTTP 에러 발생 시 예외 처리

        # 기상청 데이터는 JSON이 아닌 텍스트 형식입니다.
        text_data = response.text

        # 줄바꿈 기준으로 데이터를 나눔
        lines = text_data.split('\n')

        # '#'으로 시작하는 주석 라인과 'TM'으로 시작하는 요약 라인, 빈 라인 제거
        data_lines = [line.strip() for line in lines if not line.startswith('#') and not line.startswith('TM') and line.strip()]

        # DataFrame으로 변환 (tm, ta, td, hm 컬럼 기준)
        csv_data = '\n'.join(data_lines)
        df = pd.read_csv(io.StringIO(csv_data), names=['tm', 'ta', 'td', 'hm'])

        print("\n--- 기상청 데이터 파싱 완료 ---")
        return df

    except Exception as e:
        print(f"데이터를 불러오는 중 오류가 발생했습니다: {e}")
        return None

