"""### 10. Random Forest 모델 학습 및 성능 평가
전처리가 완료된 데이터를 바탕으로 Train/Test 셋을 분리하고, 모델을 학습한 뒤 각종 평가 지표를 출력합니다.
"""

from sklearn.model_selection import GroupShuffleSplit
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import accuracy_score, precision_score, recall_score, f1_score, roc_auc_score, confusion_matrix
from sklearn.pipeline import Pipeline
from sklearn.impute import SimpleImputer
import pandas as pd
import numpy as np

rain_cols = ['rain_1h', 'rain_3h', 'rain_6h', 'rain_12h', 'rain_24h', 'rain_48h', 'rain_72h']
terrain_cols = ['slope', 'elevation']
map_cols = ['landslide_map_value']
all_cols = rain_cols + terrain_cols + map_cols

print("\n================ 1. 데이터 검증 ================")
print(f"전체 샘플 수: {len(ml_df)} | Positive: {sum(ml_df['landslide_occurred']==1)} | Negative: {sum(ml_df['landslide_occurred']==0)}")
print("\n[피처 전체 통계량]")
display(ml_df[all_cols].describe())

print("\n[강수량 0값 및 Unique 분석]")
for col in rain_cols:
    zeros = (ml_df[col] == 0).sum()
    uniques = ml_df[col].nunique()
    print(f"{col}: 0값 {zeros}개, 고유값 {uniques}개")

print("\n[강수량 > 0 인 샘플 미리보기 (데이터 존재 여부 확인)]")
rain_exists = ml_df[ml_df['rain_72h'] > 0]
if len(rain_exists) > 0:
    display(rain_exists[['발생일자', 'landslide_occurred'] + rain_cols].head())
else:
    print("경고: 강수량 데이터가 모두 0입니다! API 호출 결과를 다시 확인해야 합니다.")

print("\n================ 2. 모델별 학습 및 비교 ================")
# 데이터 누수 방지를 위한 Group 분할 (동일 위치/사건이 분리되지 않도록)
gss = GroupShuffleSplit(n_splits=1, test_size=0.2, random_state=42)
train_idx, test_idx = next(gss.split(ml_df, ml_df['landslide_occurred'], groups=ml_df['group_id']))

train_df, test_df = ml_df.iloc[train_idx], ml_df.iloc[test_idx]
y_train, y_test = train_df['landslide_occurred'], test_df['landslide_occurred']

feature_sets = {
    "A. 강수량만 (Rain Only)": rain_cols,
    "B. 지형만 (Terrain Only)": terrain_cols,
    "C. 위험지도만 (Map Only)": map_cols,
    "D. 전체 피처 (All Features)": all_cols
}

for name, cols in feature_sets.items():
    print(f"\n>>> 모델 시나리오: {name}")
    X_train, X_test = train_df[cols], test_df[cols]

    pipe = Pipeline([
        ('imputer', SimpleImputer(strategy='median')),
        ('rf', RandomForestClassifier(n_estimators=100, max_depth=10, class_weight='balanced', random_state=42))
    ])

    pipe.fit(X_train, y_train)
    y_pred = pipe.predict(X_test)
    y_proba = pipe.predict_proba(X_test)[:, 1]

    cm = confusion_matrix(y_test, y_pred)
    print(f"Accuracy: {accuracy_score(y_test, y_pred):.4f} | Precision: {precision_score(y_test, y_pred, zero_division=0):.4f} | Recall: {recall_score(y_test, y_pred, zero_division=0):.4f} | F1: {f1_score(y_test, y_pred, zero_division=0):.4f} | ROC-AUC: {roc_auc_score(y_test, y_proba):.4f}")
    print(f"Confusion Matrix:\nTN={cm[0][0]} FP={cm[0][1]}\nFN={cm[1][0]} TP={cm[1][1]}")

    if len(cols) > 1:
        importances = pipe.named_steps['rf'].feature_importances_
        imp_df = pd.DataFrame({'Feature': cols, 'Importance': importances}).sort_values(by='Importance', ascending=False)
        print("Feature Importances:")
        for _, row in imp_df.iterrows():
            print(f"  - {row['Feature']}: {row['Importance']:.4f}")

